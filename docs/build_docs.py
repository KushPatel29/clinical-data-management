def _delta(before: int, after: int) -> str:
    if not before:
        return "n/a"
    change = (after - before) / before * 100
    return f"{change:+.1f}%"


def build_performance(results: dict) -> str:
    server = results["server"]
    lines = [
        "# Performance", "", GENERATED_BANNER,
        "Three queries, each with one specific change, measured before and after.",
        "",
        "**Every number on this page was produced by `analytics/measure_performance.py` "
        "and copied here mechanically.** None of them is an estimate and none is a "
        "percentage chosen because it read well. Re-running that script rewrites this "
        "file; if the numbers change, the file changes.",
        "",
        "## How it was measured",
        "",
        "- **Logical reads is the headline number, not elapsed time.** Elapsed time on a "
        "workstation moves with whatever else the machine is doing. Logical reads counts "
        "8 KB pages the engine touched and is stable across runs for the same plan. A "
        "change that halves elapsed time without moving logical reads made the machine "
        "quieter, not the query cheaper.",
        "- `DBCC DROPCLEANBUFFERS` and `DBCC FREEPROCCACHE` before every measurement. "
        "Without the first, the second run of a query reads pages the first run cached "
        "and every \"after\" looks faster regardless of what changed. Without the second, "
        "the engine reuses a plan compiled against the old statistics.",
        "- **Actual** execution plans (`SET STATISTICS XML ON`), not estimated ones. The "
        "`.sqlplan` files under `docs/plans/` open in SSMS or Azure Data Studio.",
        "",
        "## Environment",
        "",
        "| | |",
        "|---|---|",
        f"| Engine | {server['edition']} {server['product_version']} {server['product_level']} |",
        f"| Host | {results['host']['platform']} |",
        f"| `dw.FactObservation` | {results['fact_observation_rows']:,} rows |",
        f"| `dw.FactEncounter` | {results['fact_encounter_rows']:,} rows |",
        f"| Measured | {results['measured_at_utc']} |",
        "",
    ]

    for key, query in results["queries"].items():
        before, after = query["before"], query["after"]
        # Subtree cost is a small float; scale it so the shared percentage
        # helper is comparing integers of a similar magnitude to the others.
        cost_delta = _delta(before["estimated_subtree_cost"] * 1000,
                            after["estimated_subtree_cost"] * 1000)
        lines += [
            f"## {key} — {query['title']}", "",
            query["question"], "",
            "```sql",
            query["sql"],
            "```",
            "",
            f"**Change applied:** {query['fix']}, built in {query['fix_build_seconds']}s.",
            "",
            "```sql",
            query["fix_sql"],
            "```",
            "",
            "| Measure | Before | After | Change |",
            "|---|---:|---:|---|",
            f"| Logical reads | {before['logical_reads_total']:,} | "
            f"{after['logical_reads_total']:,} | "
            f"{_delta(before['logical_reads_total'], after['logical_reads_total'])} |",
            f"| CPU (ms) | {before['cpu_ms']:,} | {after['cpu_ms']:,} | "
            f"{_delta(before['cpu_ms'], after['cpu_ms'])} |",
            f"| Elapsed (ms) | {before['elapsed_ms']:,} | {after['elapsed_ms']:,} | "
            f"{_delta(before['elapsed_ms'], after['elapsed_ms'])} |",
            f"| Estimated subtree cost | {before['estimated_subtree_cost']} | "
            f"{after['estimated_subtree_cost']} | "
            f"{cost_delta} |",
            f"| Batch mode | {'yes' if before['batch_mode'] else 'no'} | "
            f"{'yes' if after['batch_mode'] else 'no'} | |",
            f"| Rows returned | {before['rows_returned']:,} | {after['rows_returned']:,} | "
            f"{'same' if before['rows_returned'] == after['rows_returned'] else '**DIFFERENT**'} |",
            "",
            "**Logical reads by table**",
            "",
            "| Table | Before | After |",
            "|---|---:|---:|",
        ]
        tables = sorted(set(before["logical_reads_by_table"])
                        | set(after["logical_reads_by_table"]))
        for table in tables:
            lines.append(f"| `{table}` | {before['logical_reads_by_table'].get(table, 0):,} | "
                         f"{after['logical_reads_by_table'].get(table, 0):,} |")

        lines += ["", "**Plan operators, most expensive first**", "",
                  "| | Before | After |", "|---|---|---|"]
        def render_operator(operator):
            if not operator:
                return "—"
            return "`{physical}` ({subtree_cost})".format(**operator)

        depth = max(len(before["top_operators"]), len(after["top_operators"]))
        for i in range(min(depth, 5)):
            b = before["top_operators"][i] if i < len(before["top_operators"]) else None
            a = after["top_operators"][i] if i < len(after["top_operators"]) else None
            lines.append(f"| {i + 1} | {render_operator(b)} | {render_operator(a)} |")

        before_ops = {o["physical"] for o in before["top_operators"]}
        after_ops = {o["physical"] for o in after["top_operators"]}
        gone, arrived = sorted(before_ops - after_ops), sorted(after_ops - before_ops)
        lines += ["", "**What changed in the plan**", ""]
        if gone or arrived:
            if gone:
                lines.append(f"- Gone: {', '.join(f'`{o}`' for o in gone)}")
            if arrived:
                lines.append(f"- Arrived: {', '.join(f'`{o}`' for o in arrived)}")
        else:
            lines.append("- The same operators, at different costs. Recorded as measured.")
        lines += ["",
                  f"Plans: [`{before['plan']}`]"
                  f"({Path(before['plan']).relative_to('docs').as_posix()}) · "
                  f"[`{after['plan']}`]"
                  f"({Path(after['plan']).relative_to('docs').as_posix()})"
                  if before["plan"] and after["plan"] else "",
                  ""]

    lines += [
        "## Indexes",
        "",
        "Every index in `sql/indexes/` carries the query it exists for. An index with no "
        "recorded rationale is one nobody will dare drop, and an unused index is not free: "
        "it is written on every insert, and this warehouse's inserts are the expensive part.",
        "",
    ]
    return "\n".join(lines).rstrip() + "\n"


