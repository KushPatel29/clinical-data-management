"""
Generate the documentation artefacts from the database and the measurements.

    docs/data-dictionary.md   every table and column, from INFORMATION_SCHEMA
    docs/data-map.md          FHIR element -> norm -> dw, from docs/lineage.py
    docs/erd.md               Mermaid ERDs, from sys.foreign_keys
    docs/performance.md       from docs/performance_results.json

All four are generated because all four are the kind of document that is
accurate on the day it is written and wrong within a month. A data dictionary
maintained by hand is a data dictionary that disagrees with the database, and a
data dictionary that disagrees with the database is worse than none — someone
will trust it.

The prose that cannot be generated — why a column exists, what a mapping
decided — lives in `docs/lineage.py` next to the mapping it explains, and is
verified by tests/test_docs.py against the real schema.

    python docs/build_docs.py
"""

