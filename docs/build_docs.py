def build_data_dictionary(columns, row_counts, checks, indexes, server) -> str:
    notes = {}
    for mapping in MAPPINGS:
        for target in (mapping.norm_column, mapping.dw_column):
            if target and target.count(".") == 2 and mapping.note:
                notes[target.lower()] = mapping.note
    sources = {}
    for mapping in MAPPINGS:
        for target in (mapping.norm_column, mapping.dw_column):
            if target and target.count(".") == 2:
                sources[target.lower()] = (
                    f"`{mapping.resource}.{mapping.fhir_path}`" if mapping.resource
                    else ("_derived_" if mapping.fhir_path == "derived"
                          else f"_{mapping.fhir_path}_")
                )

    lines = [
        "# Data dictionary", "", GENERATED_BANNER,
        f"Every table and column in the warehouse, read from `sys.columns` on "
        f"{server['edition'].split(' (')[0]} {server['product_version']}.",
        "",
        "The **Source** column traces each field back to the FHIR element it came from; "
        "`docs/data-map.md` shows the same relationship the other way round, from the "
        "resource down. A test asserts the two agree with the database.",
        "",
        "> Row counts describe the build this file was generated from — see "
        "`metrics.json` for which population that was. Everything else here is "
        "structure and does not move with the data.",
        "",
    ]

    by_table = defaultdict(list)
    for column in columns:
        by_table[f"{column['table_schema']}.{column['table_name']}"].append(column)

    for schema in SCHEMA_ORDER:
        tables = sorted(t for t in by_table if t.startswith(f"{schema}."))
        if not tables:
            continue
        lines += [f"## `{schema}`", "", SCHEMA_BLURB.get(schema, ""), ""]
        for table in tables:
            rows = row_counts.get(table, 0)
            lines += [f"### `{table}`", ""]
            if table in UNMAPPED_ALLOWED:
                lines += [f"_{UNMAPPED_ALLOWED[table]}_", ""]
            lines += [f"**{rows:,} rows.**", "",
                      "| Column | Type | Null | Key | Source | Notes |",
                      "|---|---|---|---|---|---|"]
            for column in by_table[table]:
                qualified = f"{table}.{column['column_name']}".lower()
                key = []
                if column["is_primary_key"]:
                    key.append("PK")
                if column["referenced_table"]:
                    key.append(f"FK &rarr; `{column['referenced_table']}`")
                if column["is_identity"]:
                    key.append("identity")
                lines.append(
                    f"| `{column['column_name']}` | `{type_label(column)}` | "
                    f"{'yes' if column['is_nullable'] else '**no**'} | "
                    f"{'<br>'.join(key) or ''} | {sources.get(qualified, '')} | "
                    f"{notes.get(qualified, '')} |"
                )
            lines.append("")

            if checks.get(table):
                lines += ["**Constraints**", ""]
                for name, definition in checks[table]:
                    lines.append(f"- `{name}` — `{definition}`")
                lines.append("")
            if indexes.get(table):
                lines += ["**Indexes**", ""]
                for name, description, _ in indexes[table]:
                    lines.append(f"- `{name}` — {description}")
                lines.append("")

    return "\n".join(lines).rstrip() + "\n"


