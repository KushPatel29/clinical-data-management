def fetch_columns(cur) -> list[dict]:
    cur.execute("""
        SELECT s.name  AS table_schema,
               t.name  AS table_name,
               c.name  AS column_name,
               c.column_id,
               ty.name AS data_type,
               c.max_length, c.precision, c.scale, c.is_nullable, c.is_identity,
               CASE WHEN pk.column_id IS NOT NULL THEN 1 ELSE 0 END AS is_primary_key,
               fk.referenced_table,
               dc.definition AS default_definition
        FROM sys.columns AS c
        JOIN sys.tables  AS t  ON t.object_id = c.object_id
        JOIN sys.schemas AS s  ON s.schema_id = t.schema_id
        JOIN sys.types   AS ty ON ty.user_type_id = c.user_type_id
        LEFT JOIN (
            SELECT ic.object_id, ic.column_id
            FROM sys.index_columns AS ic
            JOIN sys.indexes AS i ON i.object_id = ic.object_id AND i.index_id = ic.index_id
            WHERE i.is_primary_key = 1
        ) AS pk ON pk.object_id = c.object_id AND pk.column_id = c.column_id
        LEFT JOIN (
            SELECT fkc.parent_object_id, fkc.parent_column_id,
                   CONCAT(OBJECT_SCHEMA_NAME(fkc.referenced_object_id), '.',
                          OBJECT_NAME(fkc.referenced_object_id)) AS referenced_table
            FROM sys.foreign_key_columns AS fkc
        ) AS fk ON fk.parent_object_id = c.object_id AND fk.parent_column_id = c.column_id
        LEFT JOIN sys.default_constraints AS dc ON dc.object_id = c.default_object_id
        WHERE s.name IN ('raw', 'stg', 'norm', 'dw', 'meta')
        ORDER BY s.name, t.name, c.column_id
    """)
    names = [d[0] for d in cur.description]
    return [dict(zip(names, row, strict=True)) for row in cur.fetchall()]


def fetch_row_counts(cur) -> dict[str, int]:
    cur.execute("""
        SELECT CONCAT(s.name, '.', t.name) AS table_name, SUM(p.rows) AS rows
        FROM sys.tables AS t
        JOIN sys.schemas AS s ON s.schema_id = t.schema_id
        JOIN sys.partitions AS p ON p.object_id = t.object_id AND p.index_id IN (0, 1)
        WHERE s.name IN ('raw', 'stg', 'norm', 'dw', 'meta')
        GROUP BY s.name, t.name
    """)
    return {row[0]: int(row[1]) for row in cur.fetchall()}


def fetch_foreign_keys(cur) -> list[tuple[str, str, str, str]]:
    cur.execute("""
        SELECT CONCAT(OBJECT_SCHEMA_NAME(fk.parent_object_id), '.',
                      OBJECT_NAME(fk.parent_object_id))     AS child,
               CONCAT(OBJECT_SCHEMA_NAME(fk.referenced_object_id), '.',
                      OBJECT_NAME(fk.referenced_object_id)) AS parent,
               fk.name,
               COL_NAME(fkc.parent_object_id, fkc.parent_column_id) AS child_column
        FROM sys.foreign_keys AS fk
        JOIN sys.foreign_key_columns AS fkc ON fkc.constraint_object_id = fk.object_id
        WHERE OBJECT_SCHEMA_NAME(fk.parent_object_id) IN ('norm', 'dw')
        ORDER BY child, parent
    """)
    return [tuple(row) for row in cur.fetchall()]


def fetch_check_constraints(cur) -> dict[str, list[tuple[str, str]]]:
    cur.execute("""
        SELECT CONCAT(OBJECT_SCHEMA_NAME(cc.parent_object_id), '.',
                      OBJECT_NAME(cc.parent_object_id)) AS table_name,
               cc.name, cc.definition
        FROM sys.check_constraints AS cc
        WHERE OBJECT_SCHEMA_NAME(cc.parent_object_id) IN ('raw', 'stg', 'norm', 'dw', 'meta')
        ORDER BY table_name, cc.name
    """)
    grouped = defaultdict(list)
    for table, name, definition in cur.fetchall():
        grouped[table].append((name, definition))
    return grouped


def fetch_indexes(cur) -> dict[str, list[tuple[str, str, bool]]]:
    cur.execute("""
        SELECT CONCAT(s.name, '.', t.name) AS table_name,
               i.name,
               i.type_desc,
               i.is_unique,
               STUFF((SELECT ', ' + c.name
                      FROM sys.index_columns AS ic
                      JOIN sys.columns AS c ON c.object_id = ic.object_id
                                           AND c.column_id = ic.column_id
                      WHERE ic.object_id = i.object_id AND ic.index_id = i.index_id
                        AND ic.is_included_column = 0
                      ORDER BY ic.key_ordinal
                      FOR XML PATH('')), 1, 2, '') AS key_columns
        FROM sys.indexes AS i
        JOIN sys.tables  AS t ON t.object_id = i.object_id
        JOIN sys.schemas AS s ON s.schema_id = t.schema_id
        WHERE s.name IN ('raw', 'norm', 'dw') AND i.name IS NOT NULL
        ORDER BY table_name, i.name
    """)
    grouped = defaultdict(list)
    for table, name, type_desc, is_unique, key_columns in cur.fetchall():
        grouped[table].append((name, f"{type_desc}{' UNIQUE' if is_unique else ''} "
                                     f"({key_columns or 'n/a'})", bool(is_unique)))
    return grouped


def type_label(column: dict) -> str:
    name = column["data_type"]
    if name in ("nvarchar", "nchar", "varchar", "char", "varbinary", "binary"):
        length = column["max_length"]
        if length == -1:
            return f"{name}(max)"
        if name.startswith("n"):
            length //= 2
        return f"{name}({length})"
    if name in ("decimal", "numeric"):
        return f"{name}({column['precision']},{column['scale']})"
    if name in ("datetime2", "time"):
        return f"{name}({column['scale']})"
    return name


