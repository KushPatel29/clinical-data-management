def _entity(name: str) -> str:
    return name.split(".", 1)[1]


def build_erd(columns, foreign_keys, server) -> str:
    by_table = defaultdict(list)
    for column in columns:
        by_table[f"{column['table_schema']}.{column['table_name']}"].append(column)

    def diagram(schema: str, title: str) -> list[str]:
        tables = sorted(t for t in by_table if t.startswith(f"{schema}."))
        out = ["```mermaid", "erDiagram"]
        for table in tables:
            out.append(f"    {_entity(table)} {{")
            for column in by_table[table]:
                marker = "PK" if column["is_primary_key"] else (
                    "FK" if column["referenced_table"] else "")
                data_type = type_label(column).replace("(", "_").replace(")", "").replace(",", "_")
                out.append(f"        {data_type} {column['column_name']} {marker}".rstrip())
            out.append("    }")
        seen = set()
        for child, parent, _name, child_column in foreign_keys:
            if not (child.startswith(f"{schema}.") and parent.startswith(f"{schema}.")):
                continue
            key = (child, parent, child_column)
            if key in seen:
                continue
            seen.add(key)
            out.append(f"    {_entity(parent)} ||--o{{ {_entity(child)} : {child_column}")
        out.append("```")
        return [f"## {title}", ""] + out + [""]

    lines = [
        "# Entity relationship diagrams", "", GENERATED_BANNER,
        "Both diagrams are generated from `sys.columns` and `sys.foreign_keys`, so they "
        "show the relationships the engine is actually enforcing rather than the ones "
        "someone meant to create.",
        "",
    ]
    lines += diagram("norm", "`norm` — the normalised transactional model")
    lines += [
        "Every relationship above is a declared foreign key. That is the point of this "
        "layer: it is the only place in the pipeline where an encounter referencing a "
        "patient who does not exist is refused rather than reported on.",
        "",
    ]
    lines += diagram("dw", "`dw` — the dimensional model")
    lines += [
        "Five fact tables around conformed dimensions. `DimPatient` is the only Type 2 "
        "dimension; the facts join to it on a date range rather than on `is_current`, "
        "which is what makes the history mean anything.",
        "",
        "---", "",
        f"Generated against {server['edition'].split(' (')[0]} {server['product_version']}.",
    ]
    return "\n".join(lines) + "\n"


